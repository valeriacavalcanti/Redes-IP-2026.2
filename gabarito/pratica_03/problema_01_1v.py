numero = int(input('Dia da Semana: '))

if numero == 0:
    print("Domingo")
else:
    if numero == 1:
        print("Segunda-feira")
    else:
        if numero == 2:
            print("Terça-feira")
        else:
            if numero == 3:
                print("Quarta-feira")
            else:
                if numero == 4:
                    print("Quinta-feira")
                else:
                    if numero == 5:
                        print("Sexta-feira")
                    else:
                        if numero == 6:
                            print("Sábado")