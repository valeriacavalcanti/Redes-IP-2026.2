numero = int(input('Dia da Semana: '))

if numero == 0:
    print("Domingo")

if numero == 1:
    print("Segunda-feira")

if numero == 2:
    print("Terça-feira")

if numero == 3:
    print("Quarta-feira")

if numero == 4:
    print("Quinta-feira")

if numero == 5:
    print("Sexta-feira")

if numero == 6:
    print("Sábado")